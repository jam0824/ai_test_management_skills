def make_project(root: Path) -> Path:
    for rel, text in FILES.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    evidence = root / "08_テスト実行/RUN-20261101-100000/証跡"
    evidence.mkdir(parents=True, exist_ok=True)
    (evidence / "LTC-002.png").write_bytes(b"png")
    (evidence / "LTC-003.png").write_bytes(b"png")
    return root


def replace_in(root: Path, rel: str, old: str, new: str) -> None:
    path = root / rel
    text = path.read_text(encoding="utf-8")
    assert old in text, f"{old!r} が {rel} に無い"
    path.write_text(text.replace(old, new), encoding="utf-8")


def append_to(root: Path, rel: str, text: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    before = path.read_text(encoding="utf-8") if path.exists() else ""
    path.write_text(before + text, encoding="utf-8")
